// installer/build.js — build a release into dist\.
//
//   node installer/build.js                 setup program, portable zip, checksums
//   node installer/build.js --node <exe>    bundle that node.exe, not the one running this
//
// For the version in package.json it writes:
//   dist\llama-cpp-studio-<version>-setup.exe     per-user installer, no UAC prompt
//   dist\llama-cpp-studio-<version>-win-x64.zip   the same files as a portable folder
//   dist\SHA256SUMS.txt                           what the tray's updater can check against
//
// Everything else it needs ships with Windows: csc.exe from .NET Framework 4.x
// compiles the launcher, the setup program and the uninstaller, and Windows
// PowerShell renders the icon and writes the zips. No npm install, no SDK.
'use strict'

const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const crypto = require('node:crypto')
const { execFileSync } = require('node:child_process')

const ROOT = path.resolve(__dirname, '..')
const DIST = path.join(ROOT, 'dist')
const WORK = path.join(DIST, 'build')
const PRODUCT = 'llama.cpp Studio'
// Named after the product, because it is also the folder inside the portable zip.
const STAGE = path.join(WORK, PRODUCT)

// What an installed copy is made of. Tests, the bundle patcher, pack.js, the
// lint config and this installer stay behind, and so does everything under
// .gitignore's protection — data\ above all.
const APP_DIRS = ['src', 'web', 'runtime']
const APP_FILES = ['package.json', 'README.md', 'LICENSE', 'start.cmd', 'build.js', 'repair-paths.js']
// The GPU worker's scripts, not the gigabyte of CUDA runtime its dist\ collects.
const WORKER_DIR = path.join('tools', 'worker')
const WORKER_FILE = /\.(ps1|cmd|md)$/i

// Added by the build itself rather than copied.
const BUILT_FILES = ['llama-studio.exe', 'uninstall.exe']

const REQUIRED = [
  'runtime/host/boot.js',
  'runtime/client.bundle.js',
  'web/vendor/react.production.min.js',
  'web/vendor/react-dom.production.min.js',
  'src/tray.ps1',
  'src/update.ps1',
]

function walk(dir) {
  const out = []
  if (!fs.existsSync(dir)) return out
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else if (entry.isFile()) out.push(full)
  }
  return out
}

/**
 * Every file the app ships, repository-relative. Pure — no copying — so the
 * tests can check what would go out without building anything.
 */
function stagePlan(root) {
  const plan = []
  for (const dir of APP_DIRS) {
    for (const file of walk(path.join(root, dir))) {
      const rel = path.relative(root, file)
      // The bundled Node is chosen explicitly below, never whatever is lying here.
      if (rel.split(path.sep).join('/') === 'runtime/node.exe') continue
      plan.push(rel)
    }
  }
  for (const name of APP_FILES) {
    if (fs.existsSync(path.join(root, name))) plan.push(name)
  }
  const worker = path.join(root, WORKER_DIR)
  if (fs.existsSync(worker)) {
    for (const entry of fs.readdirSync(worker, { withFileTypes: true })) {
      if (entry.isFile() && WORKER_FILE.test(entry.name)) plan.push(path.join(WORKER_DIR, entry.name))
    }
  }
  return plan
}

/** The top-level names an install puts in its folder: what uninstall removes without a manifest. */
function payloadTops(plan) {
  const tops = new Set(plan.map(function (rel) { return rel.split(path.sep)[0] }))
  for (const name of BUILT_FILES) tops.add(name)
  return Array.from(tops).sort()
}

/** "https://github.com/owner/name" from package.json, or undefined. */
function repositoryUrl(pkg) {
  const raw = pkg.repository && (typeof pkg.repository === 'string' ? pkg.repository : pkg.repository.url)
  const m = /github\.com[/:]([^/]+)\/([^/]+?)(?:\.git)?\/?$/.exec(raw || '')
  return m ? 'https://github.com/' + m[1] + '/' + m[2] : undefined
}

function findCsc() {
  const windir = process.env.WINDIR || 'C:\\Windows'
  for (const fw of ['Framework64', 'Framework']) {
    const csc = path.join(windir, 'Microsoft.NET', fw, 'v4.0.30319', 'csc.exe')
    if (fs.existsSync(csc)) return csc
  }
  throw new Error('csc.exe from .NET Framework 4.x was not found under ' + windir + '\\Microsoft.NET')
}

function powershell(args) {
  return execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', ...args],
    { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] })
}

function csString(value) {
  return '"' + String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"'
}

/** Assembly attributes and the BuildInfo constants Setup.cs reads. */
function buildInfo(title, version, repoUrl, tops) {
  const four = version.split('.').concat(['0', '0', '0']).slice(0, 4).join('.')
  return [
    '// Generated by installer/build.js — do not edit.',
    'using System.Reflection;',
    '[assembly: AssemblyTitle(' + csString(title) + ')]',
    '[assembly: AssemblyProduct(' + csString(PRODUCT) + ')]',
    '[assembly: AssemblyVersion(' + csString(four) + ')]',
    '[assembly: AssemblyFileVersion(' + csString(four) + ')]',
    '[assembly: AssemblyInformationalVersion(' + csString(version) + ')]',
    'namespace LlamaStudio.Setup',
    '{',
    '    static class BuildInfo',
    '    {',
    '        public const string Version = ' + csString(version) + ';',
    '        public const string RepositoryUrl = ' + csString(repoUrl || '') + ';',
    '        public static readonly string[] PayloadTops = { ' + tops.map(csString).join(', ') + ' };',
    '    }',
    '}',
    '',
  ].join('\r\n')
}

function compile(csc, options) {
  const args = [
    '/nologo', '/target:winexe', '/platform:anycpu', '/optimize+', '/debug-',
    '/codepage:65001', '/warnaserror+',
    '/win32manifest:' + path.join(__dirname, 'app.manifest'),
    '/reference:System.dll', '/reference:System.Core.dll', '/reference:System.Drawing.dll',
    '/reference:System.Windows.Forms.dll', '/reference:System.IO.Compression.dll',
    '/reference:System.Management.dll',
    '/out:' + options.out,
  ]
  if (options.icon) args.push('/win32icon:' + options.icon)
  if (options.define) args.push('/define:' + options.define)
  for (const resource of options.resources || []) args.push('/resource:' + resource + ',' + path.basename(resource))
  args.push(...options.sources)
  try {
    execFileSync(csc, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] })
  } catch (err) {
    throw new Error('csc failed for ' + path.basename(options.out) + ':\n' + (err.stdout || '') + (err.stderr || ''))
  }
}

function sha256(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')
}

/**
 * Fail the build if a binary it compiled, or a text file it staged, names
 * this machine: the build folder or the user profile. csc writes no PDB path
 * with /debug-, and nothing in the sources should be absolute, but a release
 * goes to the public and this is cheaper than finding out from it.
 */
function assertNoLocalPaths(files) {
  const needles = []
  for (const p of [ROOT, os.homedir(), os.tmpdir()].filter(Boolean)) {
    for (const v of new Set([p, p.replace(/\\/g, '/'), p.replace(/\\/g, '\\\\')])) {
      const lower = v.toLowerCase()
      needles.push({ label: v, bytes: Buffer.from(lower, 'utf8') })
      needles.push({ label: v + ' (UTF-16)', bytes: Buffer.from(lower, 'utf16le') })
    }
  }
  for (const file of files) {
    // Lower-cased byte for byte, which covers ASCII in UTF-8 and UTF-16 alike.
    const haystack = Buffer.from(fs.readFileSync(file).toString('latin1').toLowerCase(), 'latin1')
    for (const needle of needles) {
      if (haystack.indexOf(needle.bytes) !== -1) {
        throw new Error(path.relative(ROOT, file) + ' contains a path from this machine: ' + needle.label)
      }
    }
  }
}

function argValue(name) {
  const i = process.argv.indexOf(name)
  return i === -1 ? undefined : process.argv[i + 1]
}

function main() {
  if (process.platform !== 'win32') throw new Error('the installer is built on Windows')
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'))
  const version = pkg.version
  const repoUrl = repositoryUrl(pkg)
  if (!/^\d+\.\d+\.\d+$/.test(version || '')) throw new Error('package.json version must be MAJOR.MINOR.PATCH, not ' + version)
  if (!repoUrl) console.warn('warning: package.json has no GitHub repository, so the tray cannot look for updates')

  const missing = REQUIRED.filter(function (rel) { return !fs.existsSync(path.join(ROOT, rel)) })
  if (missing.length > 0) {
    throw new Error('missing: ' + missing.join(', ')
      + '\nweb/vendor comes from `node build.js --react <node_modules dir>`; runtime/ from `node pack.js`.')
  }
  const nodeExe = path.resolve(argValue('--node') || process.execPath)
  const csc = findCsc()

  console.log('llama.cpp Studio ' + version + ' — release build')
  fs.rmSync(WORK, { recursive: true, force: true })
  fs.mkdirSync(STAGE, { recursive: true })

  // 1. The app's own files.
  const plan = stagePlan(ROOT)
  for (const rel of plan) {
    const to = path.join(STAGE, rel)
    fs.mkdirSync(path.dirname(to), { recursive: true })
    fs.copyFileSync(path.join(ROOT, rel), to)
  }
  fs.copyFileSync(nodeExe, path.join(STAGE, 'runtime', 'node.exe'))
  const nodeVersion = execFileSync(nodeExe, ['--version'], { encoding: 'utf8' }).trim()
  console.log('  staged   ' + plan.length + ' files + Node ' + nodeVersion)

  // 2. The icon, from the tray's own drawing of the mark.
  const icon = path.join(WORK, 'app.ico')
  process.stdout.write('  ' + powershell(['-File', path.join(__dirname, 'make-icon.ps1'), '-Out', icon]))

  // 3. The launcher and the uninstaller, which travel inside the payload.
  const tops = payloadTops(plan)
  const info = function (title) {
    const file = path.join(WORK, title.replace(/\W+/g, '-').toLowerCase() + '-info.cs')
    fs.writeFileSync(file, buildInfo(title, version, repoUrl, tops))
    return file
  }
  const launcher = path.join(STAGE, 'llama-studio.exe')
  const uninstaller = path.join(STAGE, 'uninstall.exe')
  compile(csc, { out: launcher, icon, sources: [info(PRODUCT), path.join(__dirname, 'Launcher.cs')] })
  compile(csc, {
    out: uninstaller, icon, define: 'UNINSTALLER', resources: [icon],
    sources: [info(PRODUCT + ' Uninstall'), path.join(__dirname, 'Setup.cs')],
  })
  console.log('  compiled llama-studio.exe, uninstall.exe')

  // 4. Zip it twice: the payload setup unpacks, and a portable folder.
  //    Entry by entry rather than ZipFile.CreateFromDirectory, which under
  //    Windows PowerShell's .NET writes "src\main.js" — a backslash the zip
  //    format does not allow, and which other unzippers keep in the file name.
  const zipScript = path.join(WORK, 'zip.ps1')
  fs.writeFileSync(zipScript, [
    'param([string]$Source, [string]$Target, [string]$Prefix)',
    "$ErrorActionPreference = 'Stop'",
    'Add-Type -AssemblyName System.IO.Compression',
    'Add-Type -AssemblyName System.IO.Compression.FileSystem',
    'if (Test-Path -LiteralPath $Target) { Remove-Item -LiteralPath $Target -Force }',
    "$root = (Resolve-Path -LiteralPath $Source).ProviderPath.TrimEnd('\\') + '\\'",
    "$zip = [System.IO.Compression.ZipFile]::Open($Target, 'Create')",
    'try {',
    '  foreach ($file in (Get-ChildItem -LiteralPath $Source -Recurse -File | Sort-Object FullName)) {',
    "    $name = $Prefix + $file.FullName.Substring($root.Length).Replace('\\', '/')",
    "    [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $file.FullName, $name, 'Optimal') | Out-Null",
    '  }',
    '} finally { $zip.Dispose() }',
    '',
  ].join('\r\n'))
  const base = 'llama-cpp-studio-' + version
  const payload = path.join(WORK, 'payload.zip')
  const portable = path.join(DIST, base + '-win-x64.zip')
  const setup = path.join(DIST, base + '-setup.exe')
  fs.mkdirSync(DIST, { recursive: true })
  for (const stale of fs.readdirSync(DIST)) {
    if (/^llama-cpp-studio-.*(-setup\.exe|-win-x64\.zip)$/.test(stale) || stale === 'SHA256SUMS.txt') {
      // An antivirus scan of the exe the last build wrote can hold it for a moment.
      fs.rmSync(path.join(DIST, stale), { force: true, maxRetries: 20, retryDelay: 250 })
    }
  }
  powershell(['-File', zipScript, '-Source', STAGE, '-Target', payload, '-Prefix', ''])
  powershell(['-File', zipScript, '-Source', STAGE, '-Target', portable, '-Prefix', PRODUCT + '/'])

  // 5. The setup program, carrying the payload.
  compile(csc, {
    out: setup, icon, resources: [payload, icon],
    sources: [info(PRODUCT + ' Setup'), path.join(__dirname, 'Setup.cs')],
  })

  const textFiles = walk(STAGE).filter(function (f) { return /\.(js|ps1|cmd|json|md|css|html|svg|webmanifest)$/i.test(f) })
  assertNoLocalPaths([launcher, uninstaller, setup].concat(textFiles))

  // 6. Checksums, in the format sha256sum -c reads.
  const outputs = [setup, portable]
  fs.writeFileSync(path.join(DIST, 'SHA256SUMS.txt'),
    outputs.map(function (f) { return sha256(f) + '  ' + path.basename(f) }).join('\n') + '\n')

  for (const f of outputs) {
    console.log('  wrote    ' + path.relative(ROOT, f) + '  (' + (fs.statSync(f).size / 1048576).toFixed(1) + ' MB)')
  }
  console.log('  wrote    ' + path.relative(ROOT, path.join(DIST, 'SHA256SUMS.txt')))
}

module.exports = {
  stagePlan, payloadTops, repositoryUrl, buildInfo, findCsc, compile, APP_DIRS, APP_FILES, BUILT_FILES,
}

if (require.main === module) {
  try {
    main()
  } catch (err) {
    console.error('release build failed: ' + (err && err.message ? err.message : err))
    process.exitCode = 1
  }
}
